export function toSkateProduct(product) {
  if (!product) return product;
  const replacement = skateCatalog[product.id];
  if (!replacement) return product;

  const variants = product.variants?.map((variant, index) => ({
    ...variant,
    name: replacement.variantOptions[index] ?? variant.name,
    color: replacement.colors[index] ?? variant.color,
  }));

  return {
    ...product,
    ...replacement,
    variants,
  };
}

export function toSkateProducts(products = []) {
  return products.map(toSkateProduct);
}

